// Helper to get nested properties
const getNestedValue = (obj: any, path: string): string | undefined => {
    return path.split('.').reduce((acc, part) => acc && acc[part], obj);
};


export const useTranslation = () => {
    const { language } = useSettings();

    const t = (key: string): string => {
        const selectedLanguageTranslations: any = translations[language];
        const fallbackLanguageTranslations: any = translations.en;

        let translatedText = getNestedValue(selectedLanguageTranslations, key);

        if (translatedText === undefined) {
            translatedText = getNestedValue(fallbackLanguageTranslations, key);
        }

        return translatedText || key;
    };

    return { t, language };
};